std::shared_ptr<IStoraged> IStoraged::fromBinder(const ::ndk::SpAIBinder& binder) {
  if (!AIBinder_associateClass(binder.get(), _g_aidl_clazz)) { return nullptr; }
  std::shared_ptr<::ndk::ICInterface> interface = ::ndk::ICInterface::asInterface(binder.get());
  if (interface) {
    return std::static_pointer_cast<IStoraged>(interface);
  }
  return ::ndk::SharedRefBase::make<BpStoraged>(binder);
}

binder_status_t IStoraged::writeToParcel(AParcel* parcel, const std::shared_ptr<IStoraged>& instance) {
  return AParcel_writeStrongBinder(parcel, instance ? instance->asBinder().get() : nullptr);
}
binder_status_t IStoraged::readFromParcel(const AParcel* parcel, std::shared_ptr<IStoraged>* instance) {
  ::ndk::SpAIBinder binder;
  binder_status_t status = AParcel_readStrongBinder(parcel, binder.getR());
  if (status != STATUS_OK) return status;
  *instance = IStoraged::fromBinder(binder);
  return STATUS_OK;
}
bool IStoraged::setDefaultImpl(std::shared_ptr<IStoraged> impl) {
  // Only one user of this interface can use this function
  // at a time. This is a heuristic to detect if two different
  // users in the same process use this function.
  assert(!IStoraged::default_impl);
  if (impl) {
    IStoraged::default_impl = impl;
    return true;
  }
  return false;
}
const std::shared_ptr<IStoraged>& IStoraged::getDefaultImpl() {
  return IStoraged::default_impl;
}
std::shared_ptr<IStoraged> IStoraged::default_impl = nullptr;
